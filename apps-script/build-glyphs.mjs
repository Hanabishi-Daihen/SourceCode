// Convert backend/schcheck/data/glyphs.json into the compact library used in the browser.
// Junk templates that would swallow a character are dropped here, once, instead of on
// every page load.
import fs from "node:fs";
import { loadCore } from "./test/load-core.mjs";

const SC = loadCore();
const src = JSON.parse(fs.readFileSync(new URL("../backend/schcheck/data/glyphs.json", import.meta.url)));

// quantise each template to integers 0..100 of its own size (the descriptor is scale free)
const data = src.map((e) => {
  const pts = e.polys.flat();
  const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  const x0 = Math.min(...xs), y0 = Math.min(...ys);
  const s = Math.max(Math.max(...xs) - x0, Math.max(...ys) - y0, 1e-6);
  const q = (v, o) => Math.round(((v - o) / s) * 100);
  return [e.ch, e.rot, e.polys.map((pl) => pl.flatMap((p) => [q(p[0], x0), q(p[1], y0)]))];
});
const lib = new SC.TemplateLibrary(data, { dropJunk: true });
const keep = new Set(lib.entries.map((e) => e.src));
console.error(`templates: ${data.length} -> ${lib.entries.length} after dropping conflicting junk`);
const kept = lib.entries.map((e) => [e.ch, e.rot, e.polys.map((pl) => pl.flat())]);
fs.mkdirSync(new URL("./build/", import.meta.url), { recursive: true });
fs.writeFileSync(new URL("./build/glyphs.js", import.meta.url),
  "/* generated by build-glyphs.mjs from backend/schcheck/data/glyphs.json */\nvar SC_GLYPHS = " + JSON.stringify(kept) + ";\n");
void keep;
